function configure_custom_code(mdl, root)
%CONFIGURE_CUSTOM_CODE 为 C Caller 配置 MINCO 自定义代码（仿真与代码生成共用）。
%   MINCO 依赖 Eigen（C++），因此自定义代码语言设为 C++，接口头文件以 extern "C" 导出。

arguments
    mdl (1,1) string
    root (1,1) string
end

eigenDir = find_eigen(root);
includeDirs = strjoin([fullfile(root, "minco"), ...
    fullfile(root, "third_party", "GCOPTER", "gcopter", "include"), eigenDir], newline);
source = fullfile(root, "minco", "minco_c_api.cpp");
header = '#include "minco_c_api.h"';

wasDirty = get_param(mdl, "Dirty");
set_param(mdl, ...
    SimTargetLang="C++", ...
    SimParseCustomCode="on", ...
    SimCustomHeaderCode=header, ...
    SimUserIncludeDirs=includeDirs, ...
    SimUserSources=source, ...
    TargetLang="C++", ...
    CustomHeaderCode=header, ...
    CustomInclude=includeDirs, ...
    CustomSource=source);
% 路径随机器而变，每次启动重新写入，不视为模型修改
set_param(mdl, Dirty=wasDirty);
end
